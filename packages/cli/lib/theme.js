import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import path from 'node:path';
import StyleDictionary from 'style-dictionary';
import { convertRaw } from '@nokgridcore/tokens/lib/convert';
import { buildCss } from '@nokgridcore/tokens/lib/css';

// The prefix NokGrid's components read. Fixed: it's compiled into @nokgridcore/ui.
const NOK = 'nok';

const namesIn = (css, prefix) => new Set([...css.matchAll(new RegExp(`--${prefix}-([a-z0-9-]+):`, 'g'))].map((m) => m[1]));

const stripGeneratedHeader = (css) => css.replace(/^\/\*\*[\s\S]*?\*\/\s*/, '');

/**
 * The token names NokGrid's components can read: every semantic token, plus
 * the non-colour primitive scales (space, radius, typography) that some
 * components use directly. Colour palette names are left to each team.
 *
 * Read from the @nokgridcore/tokens the project itself has installed (the
 * version its @nokgridcore/ui uses), falling back to the CLI's own copy.
 */
function loadContract(cwd) {
	const tryResolve = (from) => {
		try {
			return createRequire(from).resolve('@nokgridcore/tokens/css/primitives.css');
		} catch {
			return null;
		}
	};
	const fromProject = tryResolve(path.join(cwd, 'package.json'));
	const primitivesPath = fromProject ?? tryResolve(import.meta.url);
	const cssDir = path.dirname(primitivesPath);
	const pkgDir = path.resolve(cssDir, '..', '..');

	const primitives = namesIn(readFileSync(primitivesPath, 'utf8'), NOK);
	const semantic = namesIn(readFileSync(path.join(cssDir, 'semantic-light.css'), 'utf8'), NOK);
	const scales = [...primitives].filter((name) => !name.startsWith('color-'));

	return {
		semantic,
		required: new Set([...semantic, ...scales]),
		version: JSON.parse(readFileSync(path.join(pkgDir, 'package.json'), 'utf8')).version,
		source: fromProject ? 'project' : 'cli',
	};
}

function aliasBlock(selector, names, prefix) {
	return `${selector} {\n${names.map((n) => `  --${NOK}-${n}: var(--${prefix}-${n});`).join('\n')}\n}\n`;
}

/**
 * Builds a theme CSS file from a Tokens Studio export.
 *
 * @param {{ input: string, out: string, prefix?: string, cwd?: string }} options
 */
export async function buildTheme({ input, out, prefix = NOK, cwd = process.cwd() }) {
	if (!/^[a-z][a-z0-9-]*$/.test(prefix)) {
		throw new Error(`Invalid prefix "${prefix}". Use lowercase letters, numbers and hyphens, starting with a letter.`);
	}

	const inputPath = path.resolve(cwd, input);
	let raw;
	try {
		raw = JSON.parse(readFileSync(inputPath, 'utf8'));
	} catch (error) {
		throw new Error(
			error.code === 'ENOENT' ? `Can't find ${inputPath}.` : `${input} isn't valid JSON: ${error.message}`,
		);
	}

	const { setNames, ...trees } = convertRaw(raw);
	const css = await buildCss(StyleDictionary, { ...trees, prefix });
	const contract = loadContract(cwd);

	const theirs = new Set([...namesIn(css.primitives, prefix), ...namesIn(css.light, prefix)]);
	const theirsDark = namesIn(css.dark, prefix);
	const missing = [...contract.required].filter((name) => !theirs.has(name)).sort();
	const missingDark = [...contract.semantic].filter((name) => theirs.has(name) && !theirsDark.has(name)).sort();

	const relativeInput = path.relative(cwd, inputPath).split(path.sep).join('/');
	const parts = [
		`/*\n * NokGrid theme, generated by @nokgridcore/cli from ${relativeInput}.\n` +
			` * Don't edit by hand: change the values in Tokens Studio, export, and run\n` +
			` *   npx @nokgridcore/cli theme ${relativeInput}${prefix !== NOK ? ` --prefix ${prefix}` : ''}\n` +
			` * Import it after @nokgridcore/ui/styles.css.\n */\n`,
		stripGeneratedHeader(css.primitives),
		stripGeneratedHeader(css.light),
		css.dark,
	];

	// Components read --nok-* names. With another prefix, map each one to the
	// team's variable. The dark block repeats the semantic mappings: a
	// var() reference resolves where it's declared, so mappings declared only
	// on :root would carry light values into dark sections.
	if (prefix !== NOK) {
		const mapped = [...contract.required].filter((name) => theirs.has(name)).sort();
		parts.push(
			`/* NokGrid components read --${NOK}-* names; these map them to --${prefix}-*. */\n` +
				aliasBlock(':root', mapped, prefix),
			aliasBlock('[data-theme="dark"]', mapped.filter((name) => contract.semantic.has(name)), prefix),
		);
	}

	const outPath = path.resolve(cwd, out);
	writeFileSync(outPath, parts.join('\n'));

	return {
		outPath,
		missing,
		missingDark,
		tokenCount: theirs.size,
		setNames,
		contract: { size: contract.required.size, version: contract.version, source: contract.source },
	};
}
