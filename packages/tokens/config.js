import 'dotenv/config';

import StyleDictionary from 'style-dictionary';
const PREFIX = process.env.NOK_TOKEN_PREFIX ?? 'nok';

// --- Light build ---
const light = new StyleDictionary({
	source: ['src/primitives.json', 'src/semantic-light.json'],
	log: { verbosity: 'default' },
	platforms: {
		css: {
			transformGroup: 'css',
			prefix: PREFIX,
			buildPath: 'dist/css/',
			files: [
				{
					destination: 'primitives.css',
					format: 'css/variables',
					filter: (token) => token.filePath.includes('primitives'),
				},
				{
					destination: 'semantic-light.css',
					format: 'css/variables',
					selector: ':root',
					filter: (token) => token.filePath.includes('semantic-light'),
				},
			],
		},
		js: {
			transformGroup: 'js',
			buildPath: 'dist/js/',
			files: [
				{
					destination: 'tokens.js',
					format: 'javascript/es6',
					filter: (token) => token.filePath.includes('primitives'),
				},
			],
		},
		ts: {
			transformGroup: 'js',
			buildPath: 'dist/ts/',
			files: [
				{
					destination: 'tokens.d.ts',
					format: 'typescript/es6-declarations',
					filter: (token) => token.filePath.includes('primitives'),
				},
			],
		},
		tailwind: {
			transformGroup: 'js',
			buildPath: 'dist/js/',
			files: [
				{
					destination: 'tailwind-theme.js',
					format: 'tailwind/theme',
				},
			],
		},
	},
});

// Register Tailwind theme format
light.registerFormat({
	name: 'tailwind/theme',
	format: ({ dictionary }) => {
		const colors = {};
		const spacing = {};
		const borderRadius = {};
		const fontFamily = {};

		for (const token of dictionary.allTokens) {
			const cssVar = `var(--${PREFIX}-${token.path.join('-')})`;
			const [group, ...rest] = token.path;
			const key = rest.join('-');

			if (group === 'color') {
				colors[key] = cssVar;
			} else if (group === 'spacing' && rest[0] === 'radius') {
				borderRadius[rest.slice(1).join('-')] = cssVar;
			} else if (group === 'spacing' || group === 'size') {
				spacing[key] = cssVar;
			} else if (group === 'radius') {
				borderRadius[key] = cssVar;
			} else if (group === 'typography' && rest[0] === 'font-family') {
				fontFamily[rest.slice(1).join('-') || 'default'] = cssVar;
			}
		}

		const theme = { colors, spacing, borderRadius, fontFamily };

		return `// Auto-generated by Style Dictionary. Do not edit directly.\nexport const nokTailwindTheme = ${JSON.stringify(theme, null, 2)};\n`;
	},
});

// --- Dark build ---
const dark = new StyleDictionary({
	source: ['src/primitives.json', 'src/semantic-dark.json'],
	log: { verbosity: 'default' },
	platforms: {
		css: {
			transformGroup: 'css',
			prefix: PREFIX,
			buildPath: 'dist/css/',
			files: [
				{
					destination: 'semantic-dark.css',
					format: 'css/variables-dark',
					filter: (token) => token.filePath.includes('semantic-dark'),
				},
			],
		},
	},
});

// Register custom dark format before building
dark.registerFormat({
	name: 'css/variables-dark',
	format: ({ dictionary }) => {
		const vars = dictionary.allTokens.map(
			(token) =>
				`  --${PREFIX}-${token.path.join('-')}: ${token.$value ?? token.value};`,
		);
		return `[data-theme="dark"] {\n${vars.join('\n')}\n}\n`;
	},
});

await light.buildAllPlatforms();
await dark.buildAllPlatforms();
