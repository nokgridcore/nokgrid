import 'dotenv/config';

import { mkdirSync, readFileSync, writeFileSync } from 'fs';
import StyleDictionary from 'style-dictionary';
import { buildCss } from './lib/css.js';

const PREFIX = process.env.NOK_TOKEN_PREFIX ?? 'nok';

// --- CSS (shared with @nokgridcore/cli) ---
const readTree = (name) => JSON.parse(readFileSync(`src/${name}.json`, 'utf8'));
const css = await buildCss(StyleDictionary, {
	primitives: readTree('primitives'),
	light: readTree('semantic-light'),
	dark: readTree('semantic-dark'),
	prefix: PREFIX,
	verbosity: 'default',
});
mkdirSync('dist/css', { recursive: true });
writeFileSync('dist/css/primitives.css', css.primitives);
writeFileSync('dist/css/semantic-light.css', css.light);
writeFileSync('dist/css/semantic-dark.css', css.dark);

// --- JS, TypeScript and Tailwind ---
const light = new StyleDictionary({
	source: ['src/primitives.json', 'src/semantic-light.json'],
	log: { verbosity: 'default' },
	platforms: {
		js: {
			transformGroup: 'js',
			buildPath: 'dist/js/',
			files: [
				{
					destination: 'tokens.js',
					format: 'javascript/es6',
					filter: (token) => token.filePath.includes('primitives'),
				},
			],
		},
		ts: {
			transformGroup: 'js',
			buildPath: 'dist/ts/',
			files: [
				{
					destination: 'tokens.d.ts',
					format: 'typescript/es6-declarations',
					filter: (token) => token.filePath.includes('primitives'),
				},
			],
		},
		tailwind: {
			transformGroup: 'js',
			buildPath: 'dist/js/',
			files: [
				{
					destination: 'tailwind-theme.js',
					format: 'tailwind/theme',
				},
			],
		},
	},
});

// Register Tailwind theme format
light.registerFormat({
	name: 'tailwind/theme',
	format: ({ dictionary }) => {
		const colors = {};
		const spacing = {};
		const borderRadius = {};
		const fontFamily = {};
		const textStyles = {};

		for (const token of dictionary.allTokens) {
			const cssVar = `var(--${PREFIX}-${token.path.join('-')})`;
			const [group, ...rest] = token.path;
			const key = rest.join('-');

			if (group === 'color') {
				colors[key] = cssVar;
			} else if (group === 'spacing' && rest[0] === 'radius') {
				borderRadius[rest.slice(1).join('-')] = cssVar;
			} else if (group === 'spacing' || group === 'size') {
				spacing[key] = cssVar;
			} else if (group === 'radius') {
				borderRadius[key] = cssVar;
			} else if (group === 'typography' && rest[0] === 'font-family') {
				fontFamily[rest.slice(1).join('-') || 'default'] = cssVar;
			} else if (
				group === 'typography' &&
				['body', 'label', 'caption'].includes(rest[0])
			) {
				const [styleGroup, sizeName, prop] = rest;
				const styleKey = `${styleGroup}-${sizeName}`;
				textStyles[styleKey] = textStyles[styleKey] || {};
				const rawValue = token.$value ?? token.value;

				const propToKebab = {
					fontFamily: 'font-family',
					fontSize: 'font-size',
					fontWeight: 'font-weight',
					lineHeight: 'line-height',
				};
				const kebabProp = propToKebab[prop] || prop;
				const properCssVar = `var(--${PREFIX}-${group}-${styleGroup}-${sizeName}-${kebabProp})`;

				if (prop === 'fontFamily') textStyles[styleKey].fontFamily = properCssVar;
				else if (prop === 'fontSize') textStyles[styleKey].fontSize = properCssVar;
				else if (prop === 'lineHeight')
					textStyles[styleKey].lineHeight = properCssVar;
				else if (prop === 'fontWeight') {
					textStyles[styleKey].fontWeight =
						rawValue === 'medium' ? 500 : rawValue === 'regular' ? 400 : rawValue;
				}
			}
		}

		const theme = { colors, spacing, borderRadius, fontFamily, textStyles };

		return `// Auto-generated by Style Dictionary. Do not edit directly.\nexport const nokTailwindTheme = ${JSON.stringify(theme, null, 2)};\n`;
	},
});

await light.buildAllPlatforms();
